<?php

use App\Http\Controllers\Admin\ApiUsageController;
use App\Http\Controllers\Admin\AutomationActivationController;
use App\Http\Controllers\Admin\AutomationArchiveController;
use App\Http\Controllers\Admin\AutomationInterpretationController;
use App\Http\Controllers\Admin\AutomationManualRunController;
use App\Http\Controllers\Admin\AutomationPauseController;
use App\Http\Controllers\Admin\AutomationTaskController;
use App\Http\Controllers\Admin\ContentAvailabilityController;
use App\Http\Controllers\Admin\ContentController;
use App\Http\Controllers\Admin\EditorialProfileController;
use App\Http\Controllers\Admin\EditorialSourceController;
use App\Http\Controllers\Admin\MediaApiCredentialController;
use App\Http\Controllers\Admin\MediaChannelController;
use App\Http\Controllers\Admin\MediaOutletController;
use App\Http\Controllers\Admin\NewsRequestController;
use App\Http\Controllers\Admin\OrganizationController;
use App\Http\Controllers\Admin\UserController;
use App\Http\Controllers\ProfileController;
use Illuminate\Support\Facades\Route;

Route::get('/perfil', [ProfileController::class, 'edit'])->name('profile.edit');
Route::put('/perfil', [ProfileController::class, 'update'])->name('profile.update');
Route::prefix('admin')->name('admin.')->group(function (): void {
    Route::resource('usuarios', UserController::class)->parameters(['usuarios' => 'user'])->middleware('permission:USUARIOS.VER');
    Route::resource('organizaciones', OrganizationController::class)->parameters(['organizaciones' => 'organization'])->middleware('permission:USUARIOS.VER');
    Route::resource('medios', MediaOutletController::class)->parameters(['medios' => 'mediaOutlet']);
    Route::resource('medios.canales', MediaChannelController::class)->parameters(['medios' => 'mediaOutlet', 'canales' => 'mediaChannel']);
    Route::get('medios/{mediaOutlet}/credenciales/create', [MediaApiCredentialController::class, 'create'])->name('medios.credenciales.create');
    Route::post('medios/{mediaOutlet}/credenciales', [MediaApiCredentialController::class, 'store'])->name('medios.credenciales.store');
    Route::delete('medios/{mediaOutlet}/credenciales/{credential}', [MediaApiCredentialController::class, 'destroy'])->name('medios.credenciales.destroy');
    Route::get('medios/{mediaOutlet}/linea-editorial', [EditorialProfileController::class, 'edit'])->name('medios.editorial.edit');
    Route::put('medios/{mediaOutlet}/linea-editorial', [EditorialProfileController::class, 'update'])->name('medios.editorial.update');
    Route::get('medios/{mediaOutlet}/linea-editorial/historial', [EditorialProfileController::class, 'history'])->name('medios.editorial.history');
    Route::post('medios/{mediaOutlet}/linea-editorial/{profile}/restaurar/{version}', [EditorialProfileController::class, 'restore'])->name('medios.editorial.restore');
    Route::post('medios/{mediaOutlet}/linea-editorial/{profile}/fuentes', [EditorialSourceController::class, 'store'])->name('medios.editorial.sources.store');
    Route::delete('medios/{mediaOutlet}/linea-editorial/{profile}/fuentes/{source}', [EditorialSourceController::class, 'destroy'])->name('medios.editorial.sources.destroy');
    Route::get('agencia', [NewsRequestController::class, 'index'])->name('agencia.index');
    Route::get('agencia/nueva', [NewsRequestController::class, 'create'])->name('agencia.create');
    Route::post('agencia', [NewsRequestController::class, 'store'])->name('agencia.store')->middleware('throttle:10,1');
    Route::get('agencia/{newsRequest}', [NewsRequestController::class, 'show'])->name('agencia.show');
    Route::post('agencia/{newsRequest}/reintentar', [NewsRequestController::class, 'retry'])->name('agencia.retry')->middleware('throttle:5,1');
    Route::get('contenidos', [ContentController::class, 'index'])->name('contenidos.index');
    Route::get('contenidos/{content}', [ContentController::class, 'show'])->name('contenidos.show');
    Route::post('contenidos/{content}/suspender', [ContentAvailabilityController::class, 'suspend'])->name('contenidos.suspend');
    Route::post('contenidos/{content}/reactivar', [ContentAvailabilityController::class, 'reactivate'])->name('contenidos.reactivate');
    Route::post('contenidos/{content}/retirar', [ContentAvailabilityController::class, 'retire'])->name('contenidos.retire');
    Route::get('api-consumos', ApiUsageController::class)->name('api-consumos.index');
    Route::resource('piloto', AutomationTaskController::class)->parameters(['piloto' => 'automationTask'])->except('destroy');
    Route::post('piloto-interpretar', AutomationInterpretationController::class)->name('piloto.interpret')->middleware('throttle:automation-interpret');
    Route::post('piloto/{automationTask}/activar', [AutomationActivationController::class, 'store'])->name('piloto.activate');
    Route::post('piloto/{automationTask}/pausar', [AutomationPauseController::class, 'store'])->name('piloto.pause');
    Route::post('piloto/{automationTask}/archivar', [AutomationArchiveController::class, 'store'])->name('piloto.archive');
    Route::post('piloto/{automationTask}/ejecutar', [AutomationManualRunController::class, 'store'])->name('piloto.run-now')->middleware('throttle:automation-run-now');
});
